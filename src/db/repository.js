// Data access layer. No React, no UI — only SQL. `db` is an expo-sqlite
// database (useSQLiteContext()). Every multi-step write runs in a transaction.
//
// Files on disk are NOT touched here. Functions that remove rows which own
// files (purgeEntry, emptyTrash, deleteAttachment) RETURN the file names; the
// caller deletes the files only after the database commit succeeded.

import { htmlToRow } from '../utils/richText';
import { cleanTagName, tagKey } from '../utils/text';
import { cleanEmotions } from '../utils/emotions';

// expo-sqlite's withTransactionAsync is NOT exclusive: two overlapping calls on
// one connection fail with "cannot start a transaction within a transaction".
// Every write transaction goes through this per-connection queue instead.
const txQueues = new WeakMap();
export function runTx(db, fn) {
  const prev = txQueues.get(db) || Promise.resolve();
  const run = prev.catch(() => {}).then(() => db.withTransactionAsync(fn));
  txQueues.set(db, run);
  return run;
}

const nowIso = () => new Date().toISOString();

/** 32-hex-char random id generated by SQLite itself (no crypto polyfill needed). */
export async function newUid(db) {
  const row = await db.getFirstAsync('SELECT lower(hex(randomblob(16))) AS id');
  return row.id;
}

/* ------------------------------ entries ------------------------------ */

async function hydrate(db, rows, { deleted }) {
  if (!rows.length) return [];
  const delClause = deleted ? 'e.deleted_at IS NOT NULL' : 'e.deleted_at IS NULL';

  const tagRows = await db.getAllAsync(
    `SELECT et.entry_id AS entry_id, t.id AS id, t.name AS name
     FROM entry_tags et JOIN tags t ON t.id = et.tag_id
     JOIN entries e ON e.id = et.entry_id
     WHERE ${delClause}
     ORDER BY t.name COLLATE NOCASE`,
  );
  const emoRows = await db.getAllAsync(
    `SELECT em.entry_id AS entry_id, em.emotion_key AS key, em.intensity AS intensity
     FROM entry_emotions em JOIN entries e ON e.id = em.entry_id
     WHERE ${delClause}`,
  );
  const locRows = await db.getAllAsync(
    `SELECT l.* FROM locations l JOIN entries e ON e.id = l.entry_id WHERE ${delClause}`,
  );
  const attRows = await db.getAllAsync(
    `SELECT a.entry_id AS entry_id, COUNT(*) AS n
     FROM attachments a JOIN entries e ON e.id = a.entry_id
     WHERE ${delClause} GROUP BY a.entry_id`,
  );

  const tags = new Map();
  for (const r of tagRows) {
    if (!tags.has(r.entry_id)) tags.set(r.entry_id, []);
    tags.get(r.entry_id).push({ id: r.id, name: r.name });
  }
  const emotions = new Map();
  for (const r of emoRows) {
    if (!emotions.has(r.entry_id)) emotions.set(r.entry_id, []);
    emotions.get(r.entry_id).push({ key: r.key, intensity: r.intensity });
  }
  const locations = new Map(locRows.map((r) => [r.entry_id, r]));
  const counts = new Map(attRows.map((r) => [r.entry_id, r.n]));

  return rows.map((row) => ({
    ...row,
    tags: tags.get(row.id) || [],
    emotions: emotions.get(row.id) || [],
    location: locations.get(row.id) || null,
    attachmentCount: counts.get(row.id) || 0,
  }));
}

export async function listEntries(db) {
  const rows = await db.getAllAsync(
    `SELECT * FROM entries
     WHERE deleted_at IS NULL
     ORDER BY pinned DESC, journal_date DESC, updated_at DESC`,
  );
  return hydrate(db, rows, { deleted: false });
}

export async function getEntry(db, id) {
  const row = await db.getFirstAsync('SELECT * FROM entries WHERE id = ?', id);
  if (!row) return null;
  const [full] = await hydrate(db, [row], { deleted: row.deleted_at != null });
  return full || null;
}

/**
 * Create or update an entry together with its tags, emotions and location,
 * atomically. `emotions` / `location` are only touched when provided
 * (undefined = leave as is; null / [] = clear).
 * @returns {Promise<number>} entry id (resolves only after the commit)
 */
export async function saveEntry(db, input) {
  const title = (input.title ?? '').trim();
  // Rich text: the plain-text body is always derived from the sanitised HTML.
  const rich = input.bodyHtml !== undefined && input.bodyHtml !== null ? htmlToRow(input.bodyHtml) : null;
  const body = rich ? rich.body : (input.body ?? '').trim();
  const bodyHtml = rich ? rich.body_html : null;
  const formatVersion = rich ? rich.content_format_version : 1;
  const now = nowIso();
  let id = input.id ?? null;

  await runTx(db, async () => {
    if (id) {
      await db.runAsync(
        'UPDATE entries SET title=?, body=?, body_html=?, content_format_version=?, journal_date=?, mood=?, updated_at=? WHERE id=?',
        title,
        body,
        bodyHtml,
        formatVersion,
        input.journal_date,
        input.mood ?? null,
        now,
        id,
      );
    } else {
      const res = await db.runAsync(
        `INSERT INTO entries (uuid, title, body, body_html, content_format_version, journal_date, mood, favorite, pinned, created_at, updated_at)
         VALUES (lower(hex(randomblob(16))),?,?,?,?,?,?,0,0,?,?)`,
        title,
        body,
        bodyHtml,
        formatVersion,
        input.journal_date,
        input.mood ?? null,
        now,
        now,
      );
      id = res.lastInsertRowId;
    }
    if (input.tags !== undefined) await setEntryTags(db, id, input.tags || []);
    if (input.emotions !== undefined) await setEntryEmotions(db, id, input.emotions);
    if (input.location !== undefined) await setEntryLocation(db, id, input.location);
  });
  return id;
}

export async function setFavorite(db, id, value) {
  await db.runAsync('UPDATE entries SET favorite=?, updated_at=? WHERE id=?', value ? 1 : 0, nowIso(), id);
}

export async function setPinned(db, id, value) {
  await db.runAsync('UPDATE entries SET pinned=?, updated_at=? WHERE id=?', value ? 1 : 0, nowIso(), id);
}

/** Soft delete: the row and its files stay and can be restored with restoreEntry(). */
export async function softDeleteEntry(db, id) {
  await db.runAsync('UPDATE entries SET deleted_at=? WHERE id=?', nowIso(), id);
}

export async function restoreEntry(db, id) {
  await db.runAsync('UPDATE entries SET deleted_at=NULL WHERE id=?', id);
}

export async function listDeletedEntries(db) {
  const rows = await db.getAllAsync(
    'SELECT * FROM entries WHERE deleted_at IS NOT NULL ORDER BY deleted_at DESC',
  );
  return hydrate(db, rows, { deleted: true });
}

export async function countDeletedEntries(db) {
  const row = await db.getFirstAsync('SELECT COUNT(*) AS n FROM entries WHERE deleted_at IS NOT NULL');
  return row ? row.n : 0;
}

async function filesOfEntries(db, whereSql, ...params) {
  const rows = await db.getAllAsync(
    `SELECT a.file_name AS file_name, a.thumb_name AS thumb_name
     FROM attachments a JOIN entries e ON e.id = a.entry_id WHERE ${whereSql}`,
    ...params,
  );
  const files = [];
  for (const r of rows) {
    if (r.file_name) files.push(r.file_name);
    if (r.thumb_name) files.push(r.thumb_name);
  }
  return files;
}

async function deleteEntryRows(db, whereSql, ...params) {
  const sub = `(SELECT id FROM entries WHERE ${whereSql})`;
  await db.runAsync(`DELETE FROM entry_tags WHERE entry_id IN ${sub}`, ...params);
  await db.runAsync(`DELETE FROM entry_emotions WHERE entry_id IN ${sub}`, ...params);
  await db.runAsync(`DELETE FROM locations WHERE entry_id IN ${sub}`, ...params);
  await db.runAsync(`DELETE FROM attachments WHERE entry_id IN ${sub}`, ...params);
  await db.runAsync(`DELETE FROM entries WHERE ${whereSql}`, ...params);
}

/**
 * Permanent removal of one entry. Returns the attachment file names that the
 * caller must delete AFTER this resolved (the commit succeeded).
 */
export async function purgeEntry(db, id) {
  let files = [];
  await runTx(db, async () => {
    files = await filesOfEntries(db, 'e.id = ?', id);
    await deleteEntryRows(db, 'id = ?', id);
  });
  return files;
}

/** Permanently removes every trashed entry. Returns the files to delete. */
export async function emptyTrash(db) {
  let files = [];
  await runTx(db, async () => {
    files = await filesOfEntries(db, 'e.deleted_at IS NOT NULL');
    await deleteEntryRows(db, 'deleted_at IS NOT NULL');
  });
  return files;
}

/* ------------------------------- tags -------------------------------- */

async function setEntryTags(db, entryId, names) {
  const wanted = new Map();
  for (const raw of names) {
    const name = cleanTagName(raw);
    const key = tagKey(name);
    if (name && key && !wanted.has(key)) wanted.set(key, name);
  }
  await db.runAsync('DELETE FROM entry_tags WHERE entry_id=?', entryId);
  const now = nowIso();
  for (const [key, name] of wanted) {
    await db.runAsync(
      'INSERT OR IGNORE INTO tags (name, name_key, created_at, updated_at) VALUES (?,?,?,?)',
      name,
      key,
      now,
      now,
    );
    const tag = await db.getFirstAsync('SELECT id FROM tags WHERE name_key=?', key);
    await db.runAsync('INSERT OR IGNORE INTO entry_tags (entry_id, tag_id) VALUES (?,?)', entryId, tag.id);
  }
}

export async function listTags(db) {
  return db.getAllAsync(
    `SELECT t.id AS id, t.name AS name, COUNT(e.id) AS count
     FROM tags t
     LEFT JOIN entry_tags et ON et.tag_id = t.id
     LEFT JOIN entries e ON e.id = et.entry_id AND e.deleted_at IS NULL
     GROUP BY t.id
     ORDER BY count DESC, t.name COLLATE NOCASE`,
  );
}

/** Deleting a tag never deletes entries (entry_tags rows are removed). */
export async function deleteTag(db, tagId) {
  await runTx(db, async () => {
    await db.runAsync('DELETE FROM entry_tags WHERE tag_id=?', tagId);
    await db.runAsync('DELETE FROM tags WHERE id=?', tagId);
  });
}

/**
 * Rename a tag. If another tag already has the new name (case/space
 * insensitive) the two are merged: entries keep exactly one link.
 * @returns {Promise<{merged:boolean, id:number}>}
 */
export async function renameTag(db, tagId, newName) {
  const name = cleanTagName(newName);
  const key = tagKey(name);
  if (!name || !key) throw new Error('Tag name is empty');
  let result = { merged: false, id: tagId };
  await runTx(db, async () => {
    const other = await db.getFirstAsync('SELECT id FROM tags WHERE name_key=? AND id<>?', key, tagId);
    const now = nowIso();
    if (other) {
      await db.runAsync(
        'INSERT OR IGNORE INTO entry_tags (entry_id, tag_id) SELECT entry_id, ? FROM entry_tags WHERE tag_id=?',
        other.id,
        tagId,
      );
      await db.runAsync('DELETE FROM entry_tags WHERE tag_id=?', tagId);
      await db.runAsync('DELETE FROM tags WHERE id=?', tagId);
      await db.runAsync('UPDATE tags SET name=?, updated_at=? WHERE id=?', name, now, other.id);
      result = { merged: true, id: other.id };
    } else {
      await db.runAsync('UPDATE tags SET name=?, name_key=?, updated_at=? WHERE id=?', name, key, now, tagId);
    }
  });
  return result;
}

/* ------------------------------ emotions ----------------------------- */

async function setEntryEmotions(db, entryId, list) {
  await db.runAsync('DELETE FROM entry_emotions WHERE entry_id=?', entryId);
  for (const e of cleanEmotions(list)) {
    await db.runAsync(
      'INSERT INTO entry_emotions (entry_id, emotion_key, intensity) VALUES (?,?,?)',
      entryId,
      e.key,
      e.intensity,
    );
  }
}

/* ----------------------------- locations ----------------------------- */

const validCoord = (v, max) => typeof v === 'number' && Number.isFinite(v) && Math.abs(v) <= max;

export function cleanLocation(loc) {
  if (!loc) return null;
  const name = String(loc.name ?? '').trim().slice(0, 120);
  const address = String(loc.address ?? '').trim().slice(0, 240);
  const hasCoords = validCoord(loc.latitude, 90) && validCoord(loc.longitude, 180);
  if (!hasCoords && !name && !address) return null;
  return {
    latitude: hasCoords ? loc.latitude : null,
    longitude: hasCoords ? loc.longitude : null,
    name,
    address,
  };
}

/**
 * Set (or clear, with an empty string) the display name of existing saved
 * places. Coordinates and addresses are never touched.
 * @returns number of places updated
 */
export async function renameLocations(db, locationIds, name) {
  const clean = String(name ?? '').trim().slice(0, 120);
  const ids = [...new Set((locationIds || []).filter((id) => Number.isInteger(id)))];
  if (!ids.length) return 0;
  await runTx(db, async () => {
    for (const id of ids) await db.runAsync('UPDATE locations SET name=? WHERE id=?', clean, id);
  });
  return ids.length;
}

async function setEntryLocation(db, entryId, loc) {
  const clean = cleanLocation(loc);
  const existing = await db.getFirstAsync('SELECT id FROM locations WHERE entry_id=?', entryId);
  if (!clean) {
    if (existing) await db.runAsync('DELETE FROM locations WHERE entry_id=?', entryId);
    return;
  }
  if (existing) {
    await db.runAsync(
      'UPDATE locations SET latitude=?, longitude=?, name=?, address=? WHERE entry_id=?',
      clean.latitude,
      clean.longitude,
      clean.name,
      clean.address,
      entryId,
    );
  } else {
    await db.runAsync(
      `INSERT INTO locations (uuid, entry_id, latitude, longitude, name, address, created_at)
       VALUES (lower(hex(randomblob(16))),?,?,?,?,?,?)`,
      entryId,
      clean.latitude,
      clean.longitude,
      clean.name,
      clean.address,
      nowIso(),
    );
  }
}

/** Locations of live (non-trashed) entries, joined with the entry for display. */
export async function listLocations(db) {
  return db.getAllAsync(
    `SELECT l.id AS id, l.latitude AS latitude, l.longitude AS longitude, l.name AS name,
            l.address AS address, e.id AS entry_id, e.title AS entry_title,
            e.journal_date AS journal_date
     FROM locations l JOIN entries e ON e.id = l.entry_id
     WHERE e.deleted_at IS NULL
     ORDER BY e.journal_date DESC`,
  );
}

